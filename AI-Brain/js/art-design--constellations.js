  function findTarget(x,y){
    let best = null;
    let bestD = Infinity;
    for(const target of hoverTargets){
      const d = Math.hypot(target.x - x, target.y - y);
      if(d <= target.radius && d < bestD){ best = target; bestD = d; }
    }
    return best;
  }

